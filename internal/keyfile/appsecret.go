package keyfile

// The app secret binds sealed key files to this program: without it neither
// the envelope nor the peppered passphrase can be reproduced, so a stolen
// key file and passphrase file are not enough on their own. It is stored as
// two masked halves so the raw bytes never appear contiguously in the binary.
//
// This is obfuscation, not a cryptographic boundary: anyone who reverse
// engineers the binary can recover it. Changing either array makes every
// existing sealed key file unreadable; migrate them first.
var (
	appSecretMasked = [32]byte{0x3e, 0xa4, 0x3e, 0xc8, 0x67, 0x4c, 0xea, 0x5a, 0x64, 0x5d, 0xe0, 0x79, 0x5f, 0x60, 0x87, 0x96, 0x34, 0xd6, 0xe1, 0x21, 0x05, 0x41, 0x94, 0xe4, 0x38, 0x41, 0xb9, 0xda, 0xed, 0x6e, 0xcd, 0x9d}
	appSecretMask   = [32]byte{0xec, 0xf1, 0x59, 0x77, 0x9a, 0xfd, 0x79, 0x6f, 0x63, 0x4c, 0x2d, 0x28, 0x96, 0x74, 0x19, 0x58, 0x6e, 0x76, 0x6a, 0x57, 0xe8, 0xda, 0xbd, 0x92, 0xd8, 0x6a, 0x90, 0x5f, 0xd7, 0x0e, 0x79, 0xcc}
)

// appSecret reassembles the secret. Callers must not log or persist it.
func appSecret() []byte {
	secret := make([]byte, len(appSecretMasked))
	for i := range secret {
		secret[i] = appSecretMasked[i] ^ appSecretMask[i]
	}
	return secret
}
